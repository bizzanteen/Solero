QByteArray universalRootDer() {
    return QByteArray(reinterpret_cast<const char*>(kUniversalRootDer),
                      int(sizeof(kUniversalRootDer)));
}

QString thumbprint(const QByteArray& der) {
    return QString::fromLatin1(
        QCryptographicHash::hash(der, QCryptographicHash::Sha1).toHex().toUpper());
}

QByteArray certBlob(const QByteArray& der) {
    QByteArray blob;
    appendProperty(blob, kPropSha1Hash,
                   QCryptographicHash::hash(der, QCryptographicHash::Sha1));
    appendProperty(blob, kPropCertData, der);
    return blob;
}

QString registryFileText(const QByteArray& der) {
    const QByteArray blob = certBlob(der);
    // regedit's own convention: comma-separated bytes, wrapped with a trailing
    // backslash. Wine's parser accepts long lines too, but staying close to what
    // regedit emits keeps the file readable if anyone inspects it.
    QStringList bytes;
    bytes.reserve(blob.size());
    for (char c : blob)
        bytes << QString::asprintf("%02x", quint8(c));

    QString hex;
    for (int i = 0; i < bytes.size(); i += 25) {
        const QStringList chunk = bytes.mid(i, 25);
        const bool last = (i + 25 >= bytes.size());
        hex += (i == 0 ? QString() : QStringLiteral("  "))
             + chunk.join(',') + (last ? QStringLiteral("\n") : QStringLiteral(",\\\n"));
    }

    return QStringLiteral("REGEDIT4\n\n")
         + "[HKEY_LOCAL_MACHINE\\Software\\Microsoft\\SystemCertificates"
           "\\Root\\Certificates\\" + thumbprint(der) + "]\n"
         + "\"Blob\"=hex:" + hex;
}

bool isInstalled(const QString& winePrefix, const QByteArray& der) {
    QFile f(systemRegPath(winePrefix));
    if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) return false;
    // The key name is the thumbprint; its presence under Root\Certificates is what
    // Wine itself looks for. Reading the file beats shelling out to reg.exe query,
    // which costs a wineserver round-trip on every tool run.
    const QString needle = "SystemCertificates\\\\Root\\\\Certificates\\\\" + thumbprint(der);
    while (!f.atEnd())
        if (QString::fromUtf8(f.readLine()).contains(needle)) return true;
    return false;
}

Result install(const QString& winePrefix, QString* log) {
    Result r;
    const QByteArray der = universalRootDer();

    if (winePrefix.isEmpty() || !QDir(winePrefix + "/pfx").exists()) {
        r.error = "The game's Proton prefix couldn't be found.";
        return r;
    }
    if (isInstalled(winePrefix, der)) {
        r.ok = true;
        r.alreadyPresent = true;
        return r;
    }
    const QString wine = protonWine();
    if (wine.isEmpty()) {
        r.error = "Proton's bundled wine couldn't be found, so the certificate "
                  "can't be imported.";
        return r;
    }

    QTemporaryDir tmp;
    if (!tmp.isValid()) { r.error = "Couldn't create a temporary folder."; return r; }
    const QString regPath = tmp.path() + "/verisign-universal-root.reg";
    {
        QFile f(regPath);
        if (!f.open(QIODevice::WriteOnly)) {
            r.error = "Couldn't write the temporary registry file.";
            return r;
        }
        f.write(registryFileText(der).toLatin1());
    }

    qCInfo(lcTools) << "importing VeriSign Universal Root into prefix" << winePrefix;
    if (!runWine(wine, winePrefix, {"reg.exe", "import", regPath}, log)) {
        r.error = "Importing the certificate into the prefix failed.";
        return r;
    }

    // Check the registry, not the exit code: wine certutil -addstore exits 0
    // without writing anything. Query rather than re-read system.reg - wineserver
    // holds the registry in memory and flushes it later.
    if (!runWine(wine, winePrefix, {"reg.exe", "query", kRootStoreKey + thumbprint(der)},
                 log)) {
        r.error = "The certificate still isn't in the prefix's trust store after "
                  "the import.";
        return r;
    }

    // Now flush the in-memory registry to system.reg, so the cheap file-based
    // isInstalled() check sees it on later runs. wineboot returns before the
    // server has actually written the file, so wait for wineserver to exit -
    // that's what does the writing.
    runWine(wine, winePrefix, {"wineboot.exe", "-s"}, log);
    const QString wineserver = QFileInfo(wine).path() + "/wineserver";
    if (QFile::exists(wineserver))
        runWine(wineserver, winePrefix, {"-w"}, log);
    r.ok = true;
    qCInfo(lcTools) << "VeriSign Universal Root installed into prefix" << winePrefix;
    return r;
}

bool outputShowsNuGetTrustFailure(const QString& output) {
    // NU3028 = repository countersignature not trusted, NU3037 = its validity period
    // has expired. The missing root produces both, in bulk. Anchored so NU30281 and
    // friends don't match.
    static const QRegularExpression re(
        "\\bNU(3028|3037)\\b", QRegularExpression::CaseInsensitiveOption);
    return re.match(output).hasMatch();
}

bool toolLogShowsNuGetTrustFailure(const QString& installDir, const QDateTime& since) {
    QDir logs(installDir + "/logs");
    if (!logs.exists()) return false;
    for (const QFileInfo& fi : logs.entryInfoList({"*.log"}, QDir::Files)) {
        if (fi.lastModified() < since) continue; // left over from an earlier run
        QFile f(fi.absoluteFilePath());
        if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) continue;
        // These logs run to hundreds of KB and the restore errors are at the end,
        // so read the tail rather than the whole file.
        constexpr qint64 kTail = 256 * 1024;
        if (f.size() > kTail) f.seek(f.size() - kTail);
        if (outputShowsNuGetTrustFailure(QString::fromUtf8(f.readAll()))) return true;
    }
    return false;
}

