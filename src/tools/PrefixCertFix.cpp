// Windows cert-store property ids.
constexpr quint32 kPropSha1Hash = 3;
constexpr quint32 kPropCertData = 32;
constexpr quint32 kEncodingX509Asn = 1;

void appendLe32(QByteArray& out, quint32 v) {
    out.append(char(v & 0xff));
    out.append(char((v >> 8) & 0xff));
    out.append(char((v >> 16) & 0xff));
    out.append(char((v >> 24) & 0xff));
}

void appendProperty(QByteArray& out, quint32 propId, const QByteArray& data) {
    appendLe32(out, propId);
    appendLe32(out, kEncodingX509Asn);
    appendLe32(out, quint32(data.size()));
    out.append(data);
}

QString systemRegPath(const QString& winePrefix) {
    return winePrefix + "/pfx/system.reg";
}

const QString kRootStoreKey =
    QStringLiteral("HKLM\\Software\\Microsoft\\SystemCertificates\\Root\\Certificates\\");

// Proton's bundled wine. There is no host wine on a Steam Deck / Bazzite install,
// and reg.exe + wineboot are plain Wine built-ins that run fine under it (unlike
// dotnet.exe, which needs the full Proton runtime environment).
QString protonWine() {
    const QString protonDir = AppConfig::instance().detectProtonDir();
    if (protonDir.isEmpty()) return {};
    const QString wine = protonDir + "/files/bin/wine";
    return QFile::exists(wine) ? wine : QString();
}

// Runs a program (wine, or wineserver) against the prefix. False on non-zero exit.
bool runWine(const QString& wine, const QString& winePrefix,
             const QStringList& args, QString* log) {
    QProcessEnvironment env = QProcessEnvironment::systemEnvironment();
    env.insert("WINEPREFIX", winePrefix + "/pfx");
    env.insert("WINEDEBUG", "-all");

    QProcess p;
    p.setProcessChannelMode(QProcess::MergedChannels);
    p.setProcessEnvironment(env);
    p.start(wine, args);
    if (!p.waitForStarted(15000)) {
        if (log) *log += "failed to start: " + wine + "\n";
        return false;
    }
    p.waitForFinished(120000);
    if (log) *log += QString::fromUtf8(p.readAll());
    return p.exitStatus() == QProcess::NormalExit && p.exitCode() == 0;
}

